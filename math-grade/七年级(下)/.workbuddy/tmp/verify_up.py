for x, y in [(3, 1), (5, 2), (-1, 4)]:
    chk("1003Q17(2) x=%d y=%d" % (x, y), (2*x-3*y)**2 - (2*x+3*y)*(2*x-3*y), -12*x*y + 18*y*y)

# --- 18 { 3x+4y=10, 2x-3y=1 } -> x=2,y=1
chk("1003Q18 验1", 3*2 + 4*1, 10)
chk("1003Q18 验2", 2*2 - 3*1, 1)

# --- 19(1) x^3y - 4xy^3 = xy(x+2y)(x-2y)
for x, y in [(3, 1), (5, 2), (-2, 3)]:
    chk("1003Q19(1) x=%d y=%d" % (x, y), x**3*y - 4*x*y**3, x*y*(x+2*y)*(x-2*y))
# --- 19(2) (a^2+b^2)^2 - 4a^2b^2 = (a+b)^2(a-b)^2
for a, b in [(3, 1), (5, 2), (-2, 3)]:
    chk("1003Q19(2) a=%d b=%d" % (a, b), (a*a+b*b)**2 - 4*a*a*b*b, (a+b)**2 * (a-b)**2)

# --- 20 (1 - 3/(x+2)) / ((x^2-1)/(x+2)) = 1/(x+1) ; =1/3 -> x=2
for x in [2, 3, 5]:
    v = (F(1) - F(3, x+2)) / F(x*x-1, x+2)
    chk("1003Q20 x=%d" % x, v, F(1, x+1))
chk("1003Q20 解", F(3) - 1, 2)   # 1/(x+1)=1/3 -> x+1=3 -> x=2
chk("1003Q20 检验 x=2 分母", 2*2 - 1, 3)   # x^2-1 = 3 != 0

# --- 21 DE∥AC, DF∥AB -> ∠EDF=∠A ; ∠C=50, ∠EDF:∠BDE=3:2 -> ∠A=75
chk("1003Q21(2) ∠BDE", 50, 50)
