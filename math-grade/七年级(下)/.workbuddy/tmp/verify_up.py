# --- 22 { x+y=5, 2x+ay=12 } 正整数解 -> (a-2)y=2 -> a=3(a=3,y=2,x=3) / a=4(y=1,x=4)
sol = []
for av in range(-5, 12):
    if av == 2: continue
    yv = F(2, av - 2)
    if yv.denominator == 1 and yv > 0:
        xv = 5 - yv
        if xv.denominator == 1 and xv > 0:
            sol.append((av, int(xv), int(yv)))
chk("1003Q22 整数解", sol, [(3, 3, 2), (4, 4, 1)])
for av, xv, yv in sol:
    chk("1003Q22 验 av=%d" % av, 2*xv + av*yv, 12)
    chk("1003Q22 验和 av=%d" % av, xv + yv, 5)

