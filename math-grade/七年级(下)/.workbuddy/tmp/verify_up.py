"""七下三卷「解答题拔高版」逐题核算"""
from fractions import Fraction as F
import itertools

ok = 0; bad = []

def chk(name, got, want):
    global ok
    if got == want:
        ok += 1
    else:
        bad.append("%s: got %r want %r" % (name, got, want))

# ============================================================
# 1001 温州 120 分  解答 17~24 = 6,8,6,8,8,10,10,10 = 66
# ============================================================
print("=" * 20, "1001")

# --- 17(1) (-2a^2)^3 / (4a^3) + (2a)^2 * a = 2a^3
# 用多项式符号核验：取 a=2
a = 2
chk("1001Q17(1)", (-2*a**2)**3 // (4*a**3) + (2*a)**2 * a, 2*a**3)
# 代数核验：-8a^6/4a^3 = -2a^3 ; 4a^2*a = 4a^3 ; 和 = 2a^3
# --- 17(2) (a-2b)^2 - (a+b)(a-b) = -4ab + 5b^2
for a, b in [(3, 1), (5, 2), (-1, 4)]:
    chk("1001Q17(2) a=%d b=%d" % (a, b), (a-2*b)**2 - (a+b)*(a-b), -4*a*b + 5*b**2)
# --- 17(3) 2026^2 - 2024*2028 = 4
chk("1001Q17(3)", 2026**2 - 2024*2028, 4)

# --- 18(1) { 2(x+1) - 3(y-2) = 3 ; 3(x+1) + 2(y-2) = 11 }  -> x=2,y=3
# 换元 u=x+1, v=y-2: 2u-3v=3, 3u+2v=11 -> u=3,v=1
chk("1001Q18(1)", (2*3 - 3*1, 3*3 + 2*1), (3, 11))
x, y = 3 - 1, 1 + 2
chk("1001Q18(1) x", x, 2)
chk("1001Q18(1) y", y, 3)
# 代回原方程
chk("1001Q18(1) 验1", 2*(x+1) - 3*(y-2), 3)
chk("1001Q18(1) 验2", 3*(x+1) + 2*(y-2), 11)

# --- 18(2) 1/(x-2) + 3 = (x-1)/(x-2)  -> x=2 为增根，无解
# 1 + 3(x-2) = x-1 -> 2x = 4 -> x = 2
chk("1001Q18(2) 整式解", F(4, 2), 2)
chk("1001Q18(2) 增根", 2 - 2, 0)   # 分母为 0 → 增根，原方程无解

# --- 18(3) { ax+by=5, bx+ay=7 } 解 (1,2) -> a+2b=5, 2a+b=7 -> a+b=4
chk("1001Q18(3) a+b", (5 + 7) / 3, 4)
# 反解 a,b: a=3, b=1  (a+2b=5, 2a+b=7)
chk("1001Q18(3) a", (2*5 - 7) / 3, 1.0)
chk("1001Q18(3) b", (2*7 - 5) / 3, 3.0)
chk("1001Q18(3) a,b", (3, 1), (3, 1))
chk("1001Q18(3) 验1", 3*1 + 1*2, 5)   # a*x + b*y
chk("1001Q18(3) 验2", 1*1 + 3*2, 7)   # b*x + a*y

# --- 19(1) x^4 - 16 = (x^2+4)(x+2)(x-2)
for x in [2, 3, -2, 5]:
    chk("1001Q19(1) x=%d" % x, x**4 - 16, (x*x+4)*(x+2)*(x-2))
# --- 19(2) (x^2+4)^2 - 16x^2 = (x+2)^2 (x-2)^2
for x in [1, 3, -3, 7]:
    chk("1001Q19(2) x=%d" % x, (x*x+4)**2 - 16*x*x, (x+2)**2 * (x-2)**2)

# --- 20 (1 - 1/(x+1)) / (x/(x^2-1)) = x-1 ; 备选 -2,-1,1,2 排除 0,±1
for x in [-2, 2, 5]:
    v = (F(1) - F(1, x+1)) / (F(x, x*x-1))
    chk("1001Q20 x=%d" % x, v, x-1)
chk("1001Q20 x=-2 值", -2 - 1, -3)
chk("1001Q20 x=2 值", 2 - 1, 1)

# --- 21 EG⊥FG, 平分 ∠AEF、∠CFE -> ∠BEF+... 实为 ∠AEF+∠CFE=180 -> AB∥CD
# 数值验证：取 ∠AEF=t, ∠CFE=180-t; ∠GEF=t/2, ∠GFE=(180-t)/2, 和=90
for t in [100, 139.4, 150, 120]:
    chk("1001Q21 t=%.1f" % t, t/2 + (180-t)/2, 90)

# --- 22 租车 45a+30b=330 -> 3a+2b=22
sols = [(A, B) for A in range(0, 12) for B in range(0, 12) if 45*A + 30*B == 330]
chk("1001Q22 全部整数解", sols, [(0, 11), (2, 8), (4, 5), (6, 2)])
chk("1001Q22(1) 共9辆", [s for s in sols if s[0] + s[1] == 9], [(4, 5)])
ge3 = [s for s in sols if s[0] >= 3]
chk("1001Q22(2) A>=3", ge3, [(4, 5), (6, 2)])
fees = [(s, 800*s[0] + 500*s[1]) for s in ge3]
chk("1001Q22(3) 费用", fees, [((4, 5), 5700), ((6, 2), 5800)])
chk("1001Q22(3) 最低", min(f for _, f in fees), 5700)
# 满载校验
for A, B in sols:
    chk("1001Q22 载客 A=%d B=%d" % (A, B), 45*A + 30*B, 330)

# --- 23 直方图 200 人，20,?,70,50,20
freqs = [20, None, 70, 50, 20]
miss = 200 - sum(v for v in freqs if v is not None)
chk("1001Q23(1) 缺失频数", miss, 40)
chk("1001Q23(1) 频率", F(miss, 200), F(1, 5))
cum = list(itertools.accumulate([20, 40, 70, 50, 20]))
chk("1001Q23 累计", cum, [20, 60, 130, 180, 200])
# 中位数第100、101个 -> 落在第3组(2~3)
med_grp = next(i for i, c in enumerate(cum) if c >= 100)
chk("1001Q23(2) 中位数组", med_grp, 2)
chk("1001Q23(3) 不少于3小时", F(50 + 20, 200) * 1400, 490)

# --- 24 拼图 (a+b)^2 = 4ab + (a-b)^2
for A, B in [(8, 5), (6, 4), (7, 3)]:
    chk("1001Q24 恒等 a=%d b=%d" % (A, B), (A+B)**2, 4*A*B + (A-B)**2)
# (2) a+b=13, ab=40 -> a-b=3, a=8,b=5
chk("1001Q24(2) a-b", (13**2 - 4*40) ** 0.5, 3.0)
chk("1001Q24(2) a", (13 + 3) / 2, 8)
chk("1001Q24(2) b", (13 - 3) / 2, 5)
chk("1001Q24(2) ab", 8*5, 40)
# (3) 小正方形面积4, 四长方形和96 -> a-b=2, 4ab=96 -> ab=24, a+b=10 -> a=6,b=4
chk("1001Q24(3) a-b", 4 ** 0.5, 2.0)
chk("1001Q24(3) a+b", (4 + 96) ** 0.5, 10.0)
chk("1001Q24(3) a", (10 + 2) / 2, 6)
chk("1001Q24(3) b", (10 - 2) / 2, 4)
chk("1001Q24(3) 4ab", 4*6*4, 96)

